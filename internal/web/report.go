// The report is one self-contained HTML file for a time range: metadata, totals, the timeline around the range,
// areas, top allocating functions and threads, interactive flame graphs (each in its own srcdoc iframe, so their
// scripts and ids do not clash) and the raw folded stacks. It needs nothing from mhp once saved.

var esc = html.EscapeString

func signed(v int64) string {
	if v > 0 {
		return "+" + fmtValue(v, "bytes")
	}
	if v < 0 {
		return "−" + fmtValue(-v, "bytes")
	}
	return "0 B"
}

func by(v int64) string { return fmtValue(v, "bytes") }

func (s *Server) report(w http.ResponseWriter, r *http.Request) {
	if s.Range == nil || s.Stacks == nil {
		http.Error(w, "not available in replay", http.StatusNotFound)
		return
	}
	f := filter(r)
	if f.From <= 0 || f.To <= f.From {
		http.Error(w, "report needs from < to (unix ms)", http.StatusBadRequest)
		return
	}
	var meta [][2]string
	if s.Meta != nil {
		meta = s.Meta()
	}
	if note := strings.TrimSpace(r.URL.Query().Get("note")); note != "" {
		meta = append([][2]string{{"Note", note}}, meta...) // the reviewer-facing description of the case
	}
	host := "host"
	for _, kv := range meta {
		if kv[0] == "Host" {
			host = strings.Fields(kv[1])[0]
		}
	}
	from, to := time.UnixMilli(f.From), time.UnixMilli(f.To)
	w.Header().Set("Content-Type", "text/html; charset=utf-8")
	if r.URL.Query().Get("download") != "" {
		w.Header().Set("Content-Disposition", fmt.Sprintf(`attachment; filename="mhp-report-%s-%s.html"`,
			regexp.MustCompile(`[^A-Za-z0-9._-]`).ReplaceAllString(host, "_"), from.Format("20060102-150405")))
	}
	var b bytes.Buffer
	s.writeReport(&b, f, meta, from, to)
	w.Write(b.Bytes())
}

func (s *Server) writeReport(b *bytes.Buffer, f agg.Filter, meta [][2]string, from, to time.Time) {
	tot := s.Range(f)
	stacks := func(metric string) []agg.WeightedStack { // largest first, so the report is the same for the same data
		g := f
		g.Metric = metric
		st := s.Stacks(g)
		key := func(i int) string { return strings.Join(st[i].Frames, ";") }
		sort.Slice(st, func(i, j int) bool { return st[i].Value > st[j].Value || st[i].Value == st[j].Value && key(i) < key(j) })
		return st
	}
	alloc, freed, faults := stacks("range_alloc"), stacks("range_free"), stacks("range_faults")
	var threads []agg.ThreadTotals
	if s.RangeThreads != nil {
		threads = s.RangeThreads(f)
	}
	views := s.Hub.History()
	window := from.Format("2006-01-02 15:04:05") + " → " + to.Format("15:04:05") + fmt.Sprintf(" (%s)", to.Sub(from).Round(time.Second))
	// a range that starts before the first sample includes the first tick: everything recorded up to that sample
	fromStart := len(views) > 0 && f.From < views[0].T
	if fromStart {
		window = "start of the kept history → " + to.Format("2006-01-02 15:04:05")
	}

	fmt.Fprintf(b, `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>mhp memory report: %s</title><style>%s</style>
<script>try{if(localStorage.getItem('mhp-theme')==='dark')document.documentElement.dataset.theme='dark'}catch(e){}</script></head><body><main>
<button class="theme" id="theme" title="switch between the light and dark colour theme (remembered in this browser)">☾ dark</button>
<h1>Memory report <span class="sub">%s</span></h1>
<p class="lead">Generated by mhp at %s. Everything below covers the ticks in this time range only; numbers come from sampled
allocations (one sample per ~%s on average), so small values are estimates.</p>
`, esc(window), reportCSS, esc(window), esc(time.Now().Format("2006-01-02 15:04:05 MST")), esc(sampleRate(meta)))

	// metadata
	b.WriteString(`<section><h2>Context</h2><table class="kv">`)
	rows := append([][2]string{{"Time range", window}}, meta...)
	if filt := filterText(f); filt != "" {
		rows = append(rows, [2]string{"Filters", filt})
	}
	for _, kv := range rows {
		fmt.Fprintf(b, "<tr><th>%s</th><td>%s</td></tr>", esc(kv[0]), esc(kv[1]))
	}
	b.WriteString(`</table>`)
	if tot.Oldest > f.From {
		fmt.Fprintf(b, `<p class="warn">The start of the range (%s) is older than the kept timeline (%s): the totals miss the beginning.</p>`,
			esc(from.Format("15:04:05")), esc(time.UnixMilli(tot.Oldest).Format("15:04:05")))
	}
	b.WriteString(`</section>`)

	// summary
	b.WriteString(`<section><h2>Summary</h2><div class="cards">`)
	card := func(name, val, note string) {
		fmt.Fprintf(b, `<div class="card"><span>%s</span><b>%s</b><span>%s</span></div>`, esc(name), esc(val), esc(note))
	}
	card("allocated", by(tot.Alloc), fmt.Sprintf("%d samples, largest request %s", tot.Samples, by(tot.Max)))
	card("freed", by(tot.Free), "net "+signed(tot.Alloc-tot.Free))
	card("peak rise", signed(tot.PeakRise), "most traced memory held at once, above the start")
	card("page faults", by(tot.Faulted), "pages the kernel supplied (RSS growth)")
	if v0, v1, rssMax, ok := rssAround(views, f.From, f.To); ok && fromStart { // no sample before the range
		card("RSS", "→ "+by(v1.Proc["rss"]), "highest sampled in range "+by(rssMax))
		card("traced live", "→ "+by(v1.Traced), "at the end of the range")
	} else if ok {
		card("RSS", by(v0.Proc["rss"])+" → "+by(v1.Proc["rss"]), "highest sampled in range "+by(rssMax))
		card("traced live", by(v0.Traced)+" → "+by(v1.Traced), "change "+signed(v1.Traced-v0.Traced))
		if sw0, sw1 := v0.Proc["swap"], v1.Proc["swap"]; sw0 > 0 || sw1 > 0 {
			card("swap", by(sw0)+" → "+by(sw1), "swapped-out bytes of the process (VmSwap)")
		}
	}
	b.WriteString(`</div>`)
	for _, v := range views {
		if v.Paused && v.T > f.From && v.T <= f.To {
			b.WriteString(`<p class="warn">Allocation tracing was paused for part of this range: allocations made then are missing (shaded grey in the timeline).</p>`)
			break
		}
	}
	b.WriteString(`</section>`)

	// timeline
	if svg, legend := timelineSVG(views, f.From, f.To); svg != "" {
		fmt.Fprintf(b, `<section><h2>Timeline</h2><p class="note">Traced live memory by area (stacked), RSS (dashed) and the
traced peak within each tick (purple), around the selected range (shaded). Points are 1 per tick; the peak line shows
spikes that were allocated and freed between two points.</p><div class="scroll">%s</div><div class="legend">%s</div></section>`, svg, legend)
	}

	// areas
	if len(tot.Areas) > 0 {
		b.WriteString(`<section><h2>By area</h2><div class="scroll"><table><tr><th>area</th><th>allocated</th><th>freed</th><th>net</th><th>peak rise</th><th>samples</th><th>largest request</th><th>page faults</th></tr>`)
		for _, a := range tot.Areas {
			if a.Alloc == 0 && a.Free == 0 && a.Faulted == 0 {
				continue
			}
			fmt.Fprintf(b, `<tr><td>%s</td><td class="n">%s</td><td class="n">%s</td><td class="n">%s</td><td class="n">%s</td><td class="n">%d</td><td class="n">%s</td><td class="n">%s</td></tr>`,
				esc(a.Area), by(a.Alloc), by(a.Free), signed(a.Alloc-a.Free), signed(a.PeakRise), a.Samples, by(a.Max), by(a.Faulted))
			for _, c := range tot.SubAreas { // the engine's sub-areas, under it
				sub, ok := strings.CutPrefix(c.Area, a.Area+classify.Sep)
				if !ok || c.Alloc == 0 && c.Free == 0 && c.Faulted == 0 {
					continue
				}
				fmt.Fprintf(b, `<tr class="subarea"><td>└ %s</td><td class="n">%s</td><td class="n">%s</td><td class="n">%s</td><td class="n"></td><td class="n">%d</td><td class="n">%s</td><td class="n">%s</td></tr>`,
					esc(sub), by(c.Alloc), by(c.Free), signed(c.Alloc-c.Free), c.Samples, by(c.Max), by(c.Faulted))
			}
		}
		b.WriteString(`</table></div><p class="note">An allocation belongs to the nearest recognised function above it; AuditLog
owns everything called from <code>audit_log_filter::</code>. InnoDB and RocksDB are split further (└) into what they
use the memory for: buffer pool, block cache, memtables, compaction, DDL buffers, MVCC row versions and so on. Per-area peaks can happen at different moments, so they do not add
up to the total peak rise.</p></section>`)
	}

	topFunctions(b, "Top allocating functions", "allocated", alloc, tot.Alloc, true)
	topFunctions(b, "Top page-faulting functions", "faulted", faults, tot.Faulted, false)

	if len(threads) > 0 {
		b.WriteString(`<section><h2>Threads</h2><div class="scroll"><table><tr><th>TID</th><th>name</th><th>role</th><th>allocated</th><th>freed</th><th>samples</th><th>largest request</th><th>page faults</th></tr>`)
		for i, t := range threads {
			if i == 50 {
				fmt.Fprintf(b, `<tr><td colspan="8" class="note">%d more threads not shown</td></tr>`, len(threads)-50)
				break
			}
			fmt.Fprintf(b, `<tr><td class="n">%d</td><td>%s</td><td>%s</td><td class="n">%s</td><td class="n">%s</td><td class="n">%d</td><td class="n">%s</td><td class="n">%s</td></tr>`,
				t.TID, esc(t.Comm), esc(t.Role), by(t.Alloc), by(t.Free), t.Samples, by(t.Max), by(t.Faulted))
		}
		b.WriteString(`</table></div><p class="note">Frees are credited to the thread that made the allocation.</p></section>`)
	}

	// flame graphs
	b.WriteString(`<section><h2>Flame graphs</h2><p class="note">Click a frame to zoom, "Search" to highlight by regular
expression, hover for values. Allocator wrapper frames (malloc, operator new, my_malloc, ut::…) are hidden.</p>`)
	sub := window
	for _, g := range []struct {
		title  string
		st     []agg.WeightedStack
		caller bool
	}{
		{"Allocated in range: callers (allocating function at the top)", alloc, true},
		{"Allocated in range: top-down (root at the top)", alloc, false},
		{"Freed in range: callers", freed, true},
		{"Page faults in range: callers (faulting mapping at the top)", faults, true},
	} {
		if len(g.st) == 0 {
			continue
		}
		var svg bytes.Buffer
		FlameSVG(&svg, g.st, FlameOpts{Title: g.title, Subtitle: sub, Callers: g.caller, HideWrappers: true, Unit: "bytes"})
		h := "400"
		if m := reSVGHeight.FindSubmatch(svg.Bytes()); m != nil {
			h = string(m[1])
		}
		fmt.Fprintf(b, `<h3>%s</h3><iframe class="flame" style="height:calc(%spx + 18px)" srcdoc="%s"></iframe>`, esc(g.title), h,
			esc(`<!doctype html><meta charset="utf-8"><body style="margin:0">`+svg.String()))
	}
	b.WriteString(`</section>`)

	b.WriteString(`<section><h2>How to read this</h2><ul class="note">
<li><b>allocated</b>: bytes requested during the range, even if freed or reused immediately. It measures allocation work
(churn), not memory needed; summing it overstates what was ever held.</li>
<li><b>peak rise</b>: how far traced live memory rose above its value at the start of the range, at its highest point, in
allocation order. This is the extra memory needed at once.</li>
<li><b>page faults</b>: pages the kernel had to supply, which is what makes RSS grow. Memory that glibc kept and reuses
causes none; memory it returned to the kernel faults again on next use.</li>
<li>RSS can rise by less than the peak (glibc reuses free memory it holds) or stay up after it (glibc keeps freed memory).</li>
<li>Totals come from samples: with large allocations they are accurate to a few percent; a stack with a handful of
samples is an estimate.</li></ul></section>`)

	// raw data
	b.WriteString(`<section><h2>Raw folded stacks</h2><p class="note">For flamegraph.pl, speedscope or diffing: root-first,
';'-separated frames, then bytes.</p>`)
	for _, g := range []struct {
		name string
		st   []agg.WeightedStack
	}{{"allocated", alloc}, {"freed", freed}, {"page faults", faults}} {
		if len(g.st) == 0 {
			continue
		}
		var fb bytes.Buffer
		Folded(&fb, g.st, FlameOpts{})
		fmt.Fprintf(b, `<details><summary>%s (%d stacks)</summary><pre>%s</pre></details>`, esc(g.name), len(g.st), esc(fb.String()))
	}
	b.WriteString(`</section></main>` + reportThemeJS + `</body></html>`)
}

var reSVGHeight = regexp.MustCompile(`<svg [^>]*height="(\d+)"`)

func sampleRate(meta [][2]string) string {
	for _, kv := range meta {
		if kv[0] == "Sampling" {
			return kv[1]
		}
	}
	return "256 KiB"
}

func filterText(f agg.Filter) string {
	var p []string
	if f.TID != 0 {
		p = append(p, fmt.Sprintf("thread %d", f.TID))
	}
	if f.Role != "" {
		p = append(p, "role "+f.Role)
	}
	if f.Subsys != "" {
		p = append(p, "area "+f.Subsys)
	}
	return strings.Join(p, ", ")
}

// rssAround returns the views at the start and end of the range and the highest RSS sampled inside it.
func rssAround(views []live.View, from, to int64) (live.View, live.View, int64, bool) {
	var v0, v1 *live.View
	var hi int64
	for i := range views {
		v := &views[i]
		if v.T <= from {
			v0 = v
		}
		if v.T > from && v.T <= to {
			v1 = v
			hi = max(hi, v.Proc["rss"])
		}
	}
	if v1 == nil {
		return live.View{}, live.View{}, 0, false
	}
	if v0 == nil { // the range starts before the first sample
		return live.View{}, *v1, hi, true
	}
	return *v0, *v1, hi, true
}

// topFunctions lists the leaf functions (wrappers hidden) by value, each with its heaviest stack.
func topFunctions(b *bytes.Buffer, title, what string, st []agg.WeightedStack, total int64, heap bool) {
	type row struct {
		name, area string
		v, n, m    int64
		top        int64
		stack      []string
	}
	rows := map[string]*row{}
	for _, s := range st {
		if s.Value <= 0 {
			continue
		}
		var fr []string
		for _, f := range s.Frames {
			if !allocWrapper.MatchString(f) && !strings.HasPrefix(f, "[fault") {
				fr = append(fr, f)
			}
		}
		leaf := "?"
		if len(fr) > 0 {
			leaf = fr[len(fr)-1]
		}
		r := rows[leaf]
		if r == nil {
			r = &row{name: leaf, area: s.Area}
			rows[leaf] = r
		}
		r.v += s.Value
		r.n += s.N
		r.m = max(r.m, s.Max)
		if s.Value > r.top {
			r.top, r.stack = s.Value, fr
		}
	}
	if len(rows) == 0 {
		return
	}
	list := make([]*row, 0, len(rows))
	for _, r := range rows {
		list = append(list, r)
	}
	sort.Slice(list, func(i, j int) bool {
		return list[i].v > list[j].v || list[i].v == list[j].v && list[i].name < list[j].name
	})
	if len(list) > 40 {
		list = list[:40]
	}
	fmt.Fprintf(b, `<section><h2>%s</h2><div class="scroll"><table><tr><th>function (wrappers hidden)</th><th>area</th><th>%s</th><th>%%</th>`, esc(title), esc(what))
	if heap {
		b.WriteString(`<th>samples</th><th>largest request</th>`)
	} else {
		b.WriteString(`<th>pages</th>`)
	}
	b.WriteString(`</tr>`)
	for _, r := range list {
		pct := 0.0
		if total > 0 {
			pct = 100 * float64(r.v) / float64(total)
		}
		rev := make([]string, len(r.stack))
		for i, f := range r.stack {
			rev[len(r.stack)-1-i] = esc(f)
		}
		fmt.Fprintf(b, `<tr><td class="f"><details><summary>%s</summary><div class="stack">%s</div></details></td><td>%s</td><td class="n">%s</td><td class="n">%.1f</td>`,
			esc(r.name), strings.Join(rev, "<br>← "), esc(r.area), by(r.v), pct)
		if heap {
			fmt.Fprintf(b, `<td class="n">%d</td><td class="n">%s</td>`, r.n, by(r.m))
		} else {
			fmt.Fprintf(b, `<td class="n">%d</td>`, r.n)
		}
		b.WriteString(`</tr>`)
	}
	b.WriteString(`</table></div><p class="note">Click a function for its heaviest call stack (allocating function first).</p></section>`)
}

var palette = []string{"#2563eb", "#d97706", "#059669", "#db2777", "#7c3aed", "#0891b2", "#65a30d", "#dc2626", "#475569"}

// timelineSVG draws traced live memory by area around (from, to], with RSS and the in-tick peak. It returns the
// SVG and an HTML legend, or "" without enough points.
func timelineSVG(views []live.View, from, to int64) (string, string) {
	pad := max(30000, (to-from)/2)
	var pts []live.View
	for _, v := range views {
		if v.T >= from-pad && v.T <= to+pad && len(v.BySubsys) > 0 {
			pts = append(pts, v)
		}
	}
	if len(pts) < 2 {
		return "", ""
	}
	peakOf := map[string]int64{}
	for _, v := range pts {
		for k, n := range v.BySubsys {
			peakOf[k] = max(peakOf[k], n)
		}
	}
	keys := make([]string, 0, len(peakOf))
	for k := range peakOf {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool {
		return peakOf[keys[i]] > peakOf[keys[j]] || peakOf[keys[i]] == peakOf[keys[j]] && keys[i] < keys[j]
	})
	series, rest := keys, []string(nil)
	if len(keys) > 8 {
		series, rest = keys[:8], keys[8:]
		series = append(series, "other")
	}
	val := func(v live.View, k string) int64 {
		if k != "other" {
			return max(0, v.BySubsys[k])
		}
		var n int64
		for _, r := range rest {
			n += max(0, v.BySubsys[r])
		}
		return n
	}
	cum := make([][]int64, len(pts))
	var mx int64
	for i, v := range pts {
		var c int64
		for _, k := range series {
			c += val(v, k)
			cum[i] = append(cum[i], c)
		}
		mx = max(mx, c, v.Proc["rss"], v.TracedPeak, v.Proc["swap"])
	}
	top := float64(mx) * 1.1
	if top == 0 {
		top = 1
	}
	const W, H, L, R, T, B = 1100.0, 320.0, 72.0, 12.0, 10.0, 28.0
	t0, t1 := float64(pts[0].T), float64(pts[len(pts)-1].T)
	X := func(t int64) float64 { return L + (W-L-R)*(float64(t)-t0)/max(1, t1-t0) }
	Y := func(n int64) float64 { return T + (H-T-B)*(1-float64(n)/top) }
	var s strings.Builder
	fmt.Fprintf(&s, `<svg xmlns="http://www.w3.org/2000/svg" width="%.0f" height="%.0f" viewBox="0 0 %.0f %.0f" font-family="system-ui,sans-serif" font-size="11">`, W, H, W, H)
	for g := 0; g <= 4; g++ {
		n := int64(top * float64(g) / 4)
		fmt.Fprintf(&s, `<line x1="%.1f" x2="%.1f" y1="%.1f" y2="%.1f" stroke="#8884"/><text x="4" y="%.1f" fill="currentColor">%s</text>`,
			L, W-R, Y(n), Y(n), Y(n)+4, esc(by(n)))
	}
	if a, z := max(L, X(from)), min(W-R, X(to)); z > a {
		fmt.Fprintf(&s, `<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="#7c3aed" fill-opacity=".12" stroke="#7c3aed"/>`, a, T, z-a, H-T-B)
	}
	for k := len(series) - 1; k >= 0; k-- {
		var p strings.Builder
		fmt.Fprintf(&p, "%.1f,%.1f ", X(pts[0].T), Y(0))
		for i, v := range pts {
			fmt.Fprintf(&p, "%.1f,%.1f ", X(v.T), Y(cum[i][k]))
		}
		fmt.Fprintf(&p, "%.1f,%.1f", X(pts[len(pts)-1].T), Y(0))
		fmt.Fprintf(&s, `<polygon points="%s" fill="%s" fill-opacity=".85"/>`, p.String(), palette[k%len(palette)])
	}
	line := func(get func(live.View) int64, attrs string) {
		var p strings.Builder
		for _, v := range pts {
			fmt.Fprintf(&p, "%.1f,%.1f ", X(v.T), Y(get(v)))
		}
		fmt.Fprintf(&s, `<polyline points="%s" fill="none" %s/>`, p.String(), attrs)
	}
	for i, v := range pts {
		if v.Paused && i > 0 {
			fmt.Fprintf(&s, `<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="#888" fill-opacity=".25"/>`, X(pts[i-1].T), T, max(1, X(v.T)-X(pts[i-1].T)), H-T-B)
		}
	}
	line(func(v live.View) int64 { return v.Proc["rss"] }, `stroke="currentColor" stroke-dasharray="4 3"`)
	hasSwap := false
	for _, v := range pts {
		hasSwap = hasSwap || v.Proc["swap"] > 0
	}
	if hasSwap {
		line(func(v live.View) int64 { return v.Proc["swap"] }, `stroke="#d33" stroke-width="1.5" stroke-dasharray="1 3"`)
	}
	line(func(v live.View) int64 { return max(v.TracedPeak, v.Traced) }, `stroke="#7c3aed" stroke-width="1.5"`)
	for g := 0; g <= 4; g++ {
		t := pts[0].T + (pts[len(pts)-1].T-pts[0].T)*int64(g)/4
		anchor := map[int]string{0: "start", 4: "end"}[g]
		if anchor == "" {
			anchor = "middle"
		}
		fmt.Fprintf(&s, `<text x="%.1f" y="%.1f" text-anchor="%s" fill="currentColor">%s</text>`, X(t), H-8, anchor, time.UnixMilli(t).Format("15:04:05"))
	}
	s.WriteString(`</svg>`)
	var lg strings.Builder
	for k, name := range series {
		fmt.Fprintf(&lg, `<span><i style="background:%s"></i>%s</span>`, palette[k%len(palette)], esc(name))
	}
	lg.WriteString(`<span><i class="dash"></i>RSS</span><span><i style="background:#7c3aed;height:2px"></i>traced peak in tick</span>`)
	if hasSwap {
		lg.WriteString(`<span><i class="dash" style="border-top:2px dotted #d33"></i>swap</span>`)
	}
	return s.String(), lg.String()
}

