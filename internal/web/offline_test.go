// TestOfflineSnapshot checks that a server rebuilt from a snapshot (what the offline copy's WebAssembly does)
// answers every query like the live one.
func TestOfflineSnapshot(t *testing.T) {
	cls, _ := classify.New("")
	a := agg.New(cls, 60)
	hub := live.NewHub(100)
	t0 := time.Unix(1700000000, 0)
	audit := []string{"main", "do_command", "audit_log_filter::AuditLogFilter::notify_event", "malloc"}
	innodb := []string{"main", "buf_pool_init", "ut::malloc_withkey"}
	fault := []string{"main", "Field_json::store", "[fault: anon]"}
	threads := []model.ThreadStat{{TID: 7, Comm: "connection"}, {TID: 1, Comm: "mysqld"}}
	for i := 0; i < 12; i++ {
		d := []model.AllocDelta{{Stack: innodb, TID: 1, Alloc: int64(i) << 20, N: int64(i), Max: 1 << 20}}
		var rise map[string]int64
		if i == 5 || i == 6 {
			d = append(d, model.AllocDelta{Stack: audit, TID: 7, Alloc: 64 << 20, Free: 48 << 20, N: 3, Max: 32 << 20},
				model.AllocDelta{Kind: model.KindFault, Stack: fault, TID: 7, Alloc: 8 << 20, N: 2048})
			rise = map[string]int64{"AuditLog": 40 << 20}
		}
		a.Ingest(model.Tick{T: t0, Allocs: d, Threads: threads, PeakRise: 40 << 20, AreaRise: rise,
			Proc: &model.ProcStats{RSS: int64(200+i) << 20}})
		hub.Publish(a.Snapshot(t0.Add(time.Duration(i+1) * time.Second)))
	}
	ms := func(s int) int64 { return t0.Add(time.Duration(s) * time.Second).UnixMilli() }
	loc := sym.SourceLoc{File: "plugin/audit_log_filter/audit_log_filter.cc", Line: 42, Object: "/usr/lib/mysql/plugin/component_audit_log_filter.so"}
	srv := &Server{Hub: hub, Folded: a.Folded, Stacks: a.Stacks, Range: a.Range, RangeThreads: a.RangeThreads, Dump: a.Export,
		Repos: &SourceRepos{Flavor: "percona", Version: "8.4.11", Release: "11"},
		Meta:  func() [][2]string { return [][2]string{{"Host", "db1 (Linux 7.0)"}} },
		Info: func() any {
			return map[string]any{"cmd": "run", "heap": true, "faults": true, "tracer": true, "drilldown": true}
		},
		Source: func(f string) (sym.SourceLoc, bool) {
			return loc, f == "audit_log_filter::AuditLogFilter::notify_event"
		}}

	var buf bytes.Buffer
	sn, err := srv.Snapshot()
	if err != nil {
		t.Fatal(err)
	}
	if err := sn.Encode(&buf); err != nil {
		t.Fatal(err)
	}
	t.Logf("snapshot: %d bytes gzipped, %d ticks, %d stacks", buf.Len(), len(sn.Agg.Ticks), len(sn.Agg.Stacks))
	sn2, err := DecodeSnapshot(&buf)
	if err != nil {
		t.Fatal(err)
	}
	off, err := OfflineServer(sn2)
	if err != nil {
		t.Fatal(err)
	}
	get := func(s *Server, url string) (int, string) {
		rec := httptest.NewRecorder()
		s.Handler().ServeHTTP(rec, httptest.NewRequest("GET", url, nil))
		return rec.Code, rec.Body.String()
	}
	gen := regexp.MustCompile(`Generated by mhp at [^.]*\.|\d{4}-\d\d-\d\d \d\d:\d\d:\d\d(?: MST)?`) // time of the request
	norm := func(url, body string) string {
		if strings.HasPrefix(url, "/stacks") { // map order
			var st []agg.WeightedStack
			json.Unmarshal([]byte(body), &st)
			sort.Slice(st, func(i, j int) bool { return strings.Join(st[i].Frames, ";") < strings.Join(st[j].Frames, ";") })
			b, _ := json.Marshal(st)
			return string(b)
		}
		if strings.HasPrefix(url, "/folded") {
			l := strings.Split(body, "\n")
			sort.Strings(l)
			return strings.Join(l, "\n")
		}
		return gen.ReplaceAllString(body, "")
	}
	rng := func(m string) string { return "&from=" + itoa(ms(4)) + "&to=" + itoa(ms(7)) + "&metric=" + m }
	for _, url := range []string{"/history", "/range?" + rng(""), "/range?tid=7" + rng(""), "/range?role=connection" + rng(""),
		"/meta", "/stacks?metric=live", "/stacks?metric=growth", "/stacks?metric=alloc", "/stacks?metric=faults", "/stacks?metric=faults_window",
		"/stacks?" + rng("range_alloc"), "/stacks?" + rng("range_free"), "/stacks?" + rng("range_net"), "/stacks?" + rng("range_faults"),
		"/stacks?subsys=AuditLog" + rng("range_alloc"), "/folded", "/folded?metric=live",
		"/source?f=audit_log_filter::AuditLogFilter::notify_event", "/source?f=main",
		"/report.html?from=" + itoa(ms(4)) + "&to=" + itoa(ms(7)), "/flame.svg?view=callers" + rng("range_alloc")} {
		c1, b1 := get(srv, url)
		c2, b2 := get(off, url)
		if c1 != http.StatusOK || c2 != c1 {
			t.Errorf("%s: status live %d offline %d", url, c1, c2)
		}
		if n1, n2 := norm(url, b1), norm(url, b2); n1 != n2 {
			i := 0
			for i < len(n1) && i < len(n2) && n1[i] == n2[i] {
				i++
			}
			lo := max(0, i-150)
			t.Errorf("%s differs at %d:\nlive    %.300s\noffline %.300s", url, i, n1[lo:], n2[lo:])
		}
	}
	// the range really has data, and the tracer is off offline
	if _, b := get(off, "/range?"+rng("")); !strings.Contains(b, `"area":"AuditLog","alloc":134217728`) {
		t.Errorf("offline range: %s", b)
	}
	if _, b := get(off, "/info"); !strings.Contains(b, `"tracer":false`) || !strings.Contains(b, `"offline":{`) {
		t.Errorf("offline info: %s", b)
	}
	if _, b := get(off, "/source?f=audit_log_filter::AuditLogFilter::notify_event"); !strings.Contains(b, "Percona-Server-8.4.11-11/plugin/audit_log_filter/audit_log_filter.cc#L42") {
		t.Errorf("offline source: %s", b)
	}
}

func itoa(n int64) string { b, _ := json.Marshal(n); return string(b) }
